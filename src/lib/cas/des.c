void des_key_expand(const unsigned char in[DES_KEY56_LEN], unsigned char out[DES_BLOCK_LEN]) {
  uint64_t v = 0;
  for (int i = 0; i < DES_KEY56_LEN; i++) v = (v << 8) | in[i];
  for (int i = 0; i < DES_BLOCK_LEN; i++) {
    unsigned b = (unsigned)((v >> (49 - 7 * i)) & 0x7F) << 1;
    out[i] = (unsigned char)(b | (__builtin_parity(b) ? 0U : 1U));
  }
}

static inline uint32_t ks_lookup(const uint32_t t[7][16], uint32_t half) {
  return t[0][(half >> 24) & 15] | t[1][(half >> 20) & 15] | t[2][(half >> 16) & 15] | t[3][(half >> 12) & 15] | t[4][(half >> 8) & 15] | t[5][(half >> 4) & 15] | t[6][half & 15];
}

void des_set_key(des_key_t *ks, const unsigned char key[DES_BLOCK_LEN]) {
  uint64_t x = 0;
  uint64_t t;
  uint32_t c, d;
  for (int i = DES_BLOCK_LEN - 1; i >= 0; i--) x = (x << 8) | key[i];
  /* PC-1 8x8 bit transpose, rows reversed */
  t = (x ^ (x >> 7)) & 0x00AA00AA00AA00AAULL;
  x ^= t ^ (t << 7);
  t = (x ^ (x >> 14)) & 0x0000CCCC0000CCCCULL;
  x ^= t ^ (t << 14);
  t = (x ^ (x >> 28)) & 0x00000000F0F0F0F0ULL;
  x ^= t ^ (t << 28);
  c = (uint32_t)(x >> 36);
  d = (uint32_t)((x >> 8) & 0xFF) << 20 | (uint32_t)((x >> 16) & 0xFF) << 12 | (uint32_t)((x >> 24) & 0xFF) << 4 | (uint32_t)((x >> 32) & 0x0F);
  for (int i = 0; i < 16; i++) {
    unsigned s = 1 + ((0x7EFCU >> i) & 1);
    uint32_t wc, wd;
    c = ((c << s) | (c >> (28 - s))) & 0x0FFFFFFF;
    d = ((d << s) | (d >> (28 - s))) & 0x0FFFFFFF;
    wc = ks_lookup(des_ks_c, c);
    wd = ks_lookup(des_ks_d, d);
    ks->k[2 * i] = (wc & 0xFFFF0000) | (wd >> 16);
    ks->k[2 * i + 1] = (wc << 16) | (wd & 0xFFFF);
  }
}

static inline uint32_t rol32(uint32_t v, unsigned n) { return (v << n) | (v >> (32 - n)); }

static inline void des_ip(uint32_t *lp, uint32_t *rp) {
  uint32_t l = *lp, r = *rp, t;
  t = ((l >> 4) ^ r) & 0x0F0F0F0F;
  r ^= t;
  l ^= t << 4;
  t = ((l >> 16) ^ r) & 0x0000FFFF;
  r ^= t;
  l ^= t << 16;
  t = ((r >> 2) ^ l) & 0x33333333;
  l ^= t;
  r ^= t << 2;
  t = ((r >> 8) ^ l) & 0x00FF00FF;
  l ^= t;
  r = rol32(r ^ (t << 8), 1);
  t = (l ^ r) & 0xAAAAAAAA;
  l = rol32(l ^ t, 1);
  r ^= t;
  *lp = l;
  *rp = r;
}

static inline void des_fp(uint32_t *lp, uint32_t *rp) {
  uint32_t l = rol32(*lp, 31), r = *rp, t;
  t = (l ^ r) & 0xAAAAAAAA;
  l ^= t;
  r = rol32(r ^ t, 31);
  t = ((r >> 8) ^ l) & 0x00FF00FF;
  l ^= t;
  r ^= t << 8;
  t = ((r >> 2) ^ l) & 0x33333333;
  l ^= t;
  r ^= t << 2;
  t = ((l >> 16) ^ r) & 0x0000FFFF;
  r ^= t;
  l ^= t << 16;
  t = ((l >> 4) ^ r) & 0x0F0F0F0F;
  r ^= t;
  l ^= t << 4;
  *lp = l;
  *rp = r;
}

static inline uint32_t des_f(uint32_t r, uint32_t k0, uint32_t k1) {
  uint32_t a = rol32(r, 28) ^ k0;
  uint32_t b = r ^ k1;
  return des_sp[6][a & 63] | des_sp[4][(a >> 8) & 63] | des_sp[2][(a >> 16) & 63] | des_sp[0][(a >> 24) & 63] |
    des_sp[7][b & 63] | des_sp[5][(b >> 8) & 63] | des_sp[3][(b >> 16) & 63] | des_sp[1][(b >> 24) & 63];
}

/* FP/IP cancel between EDE stages: output feeds next stage */
static inline void des_rounds(const des_key_t *ks, uint32_t *lp, uint32_t *rp, int decrypt) {
  uint32_t l = *lp, r = *rp;
  for (int i = 0; i < 8; i++) {
    int a = decrypt ? 30 - 4 * i : 4 * i;
    int b = decrypt ? 28 - 4 * i : 4 * i + 2;
    l ^= des_f(r, ks->k[a], ks->k[a + 1]);
    r ^= des_f(l, ks->k[b], ks->k[b + 1]);
  }
  *lp = r;
  *rp = l;
}

static void des_crypt(const des_key_t *ks, const unsigned char in[DES_BLOCK_LEN], unsigned char out[DES_BLOCK_LEN], int decrypt) {
  uint32_t l = be32_get(in), r = be32_get(in + 4);
  des_ip(&l, &r);
  des_rounds(ks, &l, &r, decrypt);
  des_fp(&l, &r);
  be32_put(out, l);
  be32_put(out + 4, r);
}

void des_encrypt(const des_key_t *ks, const unsigned char in[DES_BLOCK_LEN], unsigned char out[DES_BLOCK_LEN]) { des_crypt(ks, in, out, 0); }

void des_decrypt(const des_key_t *ks, const unsigned char in[DES_BLOCK_LEN], unsigned char out[DES_BLOCK_LEN]) { des_crypt(ks, in, out, 1); }

void des3_decrypt(const des_key_t *k1, const des_key_t *k2, const des_key_t *k3, const unsigned char in[DES_BLOCK_LEN], unsigned char out[DES_BLOCK_LEN]) {
  uint32_t l = be32_get(in), r = be32_get(in + 4);
  des_ip(&l, &r);
  des_rounds(k3, &l, &r, 1);
  des_rounds(k2, &l, &r, 0);
  des_rounds(k1, &l, &r, 1);
  des_fp(&l, &r);
  be32_put(out, l);
  be32_put(out + 4, r);
}
