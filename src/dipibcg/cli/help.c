#include <stdio.h>

#include "priv.h"
#include "../version.h"

void bcg_print_help(void) {
  printf(
    "usage: %s -a -s <schema> -i <input> [-M <map.csv>] -m <mcast>:<port> [options]\n"
    "       %s -l -s <schema> -m <mcast>:<port> [options]\n\n"
    "DVB-IPI EPG/BCG (ETSI TS 102 539): announce TV-Anytime fragments on multicast,\n"
    "BiM-encoded or as plain XML, from an xmltv guide, a TVA XML document or a BiM\n"
    "stream, or listen for them and write the received guide as xmltv, TVA XML or BiM\n\n"
    "options:\n"
    "  -a, --announce         headend mode: read -i, transmit on -m\n"
    "  -l, --listen           client mode: receive on -m, write -o\n"
    "  -m, --mcast <g>:<p>    multicast group:port ([addr6]:port for v6)\n"
    "  -I, --iface <iface>    multicast interface\n"
    "  -f, --format <fmt>     announce: input xmltv|tva|bim (default xmltv), listen: output\n"
    "                         xmltv|tva|bim (default xmltv). tva is TVA XML, bim a dipibim stream\n"
    "  -s, --schema <path>    TV-Anytime schema file, or directory searched for the schema of the\n"
    "                         namespace (announce: of the xmltv output, listen: of the stream).\n"
    "                         Repeatable, of several files the one declaring the namespace\n"
    "                         is used. Schemas of further namespaces of a stream or a tva\n"
    "                         document are found the same way. Required\n"
    "  -v, --verbose          periodic stats on stderr\n"
    "      --color <when>     auto|always|never (default auto)\n"
    "  -d, --daemonize        fork to background after startup, detach from terminal\n"
    "  -c, --config <path>    YAML config file (default: %s, if present)\n"
    "      --config-strict    fail on config file issues instead of warnings\n"
    "      --configtest       check the config file, then exit\n"
    "      --metrics <path>   socket for metrics (default: /run/dvbipitools/metrics.sock)\n"
    "      --metrics-id <id>  stable instance id; metrics disabled unless set\n"
    "      --metrics-interval <s> snapshot interval in seconds (default: 5)\n"
    "  -h, --help             this help\n"
    "      --version          print version and exit\n\n"
    "listen mode options:\n"
    "  -t, --timeout <s>      stop after N seconds, 0 = until signal (default 35)\n"
    "  -o, --output <path>    xmltv output path, - for stdout (default)\n"
    "  -C, --csv-map <path>   also write a mapping csv (feeds back into -M)\n\n"
    "announce mode options:\n"
    "  -i, --input <path>     input of -f (required)\n"
    "  -M, --map <path>       xmltv id -> uri,tsid,onid,sid csv (required for -f xmltv)\n"
    "      --encoding <enc>   bim|plain (default bim). plain: TVA XML with compr=000\n"
    "  -w, --window <hours>   only events starting within this (default 24)\n"
    "      --dscp <v>         output DSCP marking: video-high|video-low|voice|\n"
    "                         signalling|best-effort|0..63 (default: signalling)\n"
    "  -T, --ttl <n>          multicast TTL / hop limit, 1..255 (default 16)\n"
    "  -t, --interval <s>     repeat interval (default 5)\n"
    "      --refresh <n>      resend unchanged segments every Nth cycle (default 1)\n"
    "  -Z, --compress         zlib-compress BCG containers (RFC 1950)\n"
    "      --publisher <d>/<n> send TVAMain with this publisher\n"
    "      --lang <lang>      TVAMain xml:lang, requires --publisher\n"
    "      --index <kinds>    pi-crid,pi-title,schedule-time,schedule-title\n"
    "      --dvb-locator      optimized locator coding where representable\n"
    "      --dvb-duration     minute coding of durations where exact\n"
    "      --dvb-pubtime      PublishedTime coding of dateTime where representable\n\n"
    "examples:\n"
    "  %s -a -s schemas/ -i guide.xml -M mapping.csv -m 239.255.0.2:3938\n"
    "  %s -l -s schemas/ -m 239.255.0.2:3938 -o guide.xml -C mapping.csv\n",
    TOOL_NAME, TOOL_NAME, DEFAULT_CONFIG_PATH, TOOL_NAME, TOOL_NAME);
}
